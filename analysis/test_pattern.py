"""Step 3: do Korean entertainers match the "연예인 사주" patterns that the two
source articles agree on?  Rules were fixed in the progress log BEFORE running.

A1 식상 : month-branch or day-branch main qi is 식신/상관 relative to the day stem
B  도화 : 도화 branch of the year-branch or day-branch group is among {년지,월지,일지}
C      : A1 and B together

Baseline: for a person born in year Y, the share of calendar days of Y on which the
rule holds. Expected count = sum over people; z-test with Poisson-binomial variance.
"""
import sys
from datetime import date

import numpy as np
import pandas as pd
import sxtwl
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from saju_kst import YG, MG  # KST 절기 (see saju_kst.py)
from saju_kst import is_term_day
import os
DROP = os.environ.get('SAJU_DROP_TERM_DAYS') == '1'  # main analysis: leave out 절-day births and the same days of the baseline calendar
from scipy import stats

SRC, OUT_MD = sys.argv[1], sys.argv[2]
GAN = list("갑을병정무기경신임계")
JI = list("자축인묘진사오미신유술해")
ELEM = {"갑": 0, "을": 0, "병": 1, "정": 1, "무": 2, "기": 2, "경": 3, "신": 3, "임": 4, "계": 4}
YANG = {g: (i % 2 == 0) for i, g in enumerate(GAN)}
BONGI = dict(zip("자축인묘진사오미신유술해", "계기갑을무병정기경신무임"))
JIE_ODD = set(range(1, 24, 2))
DOHWA = {}
for grp, tgt in (("인오술", "묘"), ("사유축", "오"), ("신자진", "유"), ("해묘미", "자")):
    for b in grp:
        DOHWA[b] = tgt


def is_siksang(ilgan, branch):
    s = BONGI[branch]
    return ELEM[s] == (ELEM[ilgan] + 1) % 5  # element generated by the day stem


def rules(year_p, month_p, day_p):
    ilgan, dj = day_p[0], day_p[1]
    mj, yj = month_p[1], year_p[1]
    a1 = is_siksang(ilgan, mj) or is_siksang(ilgan, dj)
    br = {yj, mj, dj}
    b = (DOHWA[yj] in br) or (DOHWA[dj] in br)
    return a1, b, (a1 and b)


# ---- per-year calendar baseline ------------------------------------------------
cache = {}


def year_table(y):
    if y in cache:
        return cache[y]
    n = 366 if (y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)) else 365
    base = date(y, 1, 1).toordinal()
    jie = {}
    for k in range(-1, n + 1):
        dt = date.fromordinal(base + k)
        d = sxtwl.fromSolar(dt.year, dt.month, dt.day)
        jie[k] = bool(d.hasJieQi() and d.getJieQi() in JIE_ODD)
    rows = []
    for k in range(n):
        dt = date.fromordinal(base + k)
        if DROP and is_term_day(dt):
            continue
        d = sxtwl.fromSolar(dt.year, dt.month, dt.day)
        yg, mg, dg = YG(dt), MG(dt), d.getDayGZ()
        yp = GAN[yg.tg] + JI[yg.dz]
        mp = GAN[mg.tg] + JI[mg.dz]
        dp = GAN[dg.tg] + JI[dg.dz]
        a1, b, c = rules(yp, mp, dp)
        near = jie[k - 1] or jie[k] or jie[k + 1]
        rows.append((a1, b, c, near))
    arr = np.array(rows, dtype=bool)
    cache[y] = arr
    return arr


def evaluate(sub, name, drop_near):
    res = {}
    for j, rule in enumerate(["A1 식상(월지·일지)", "B 도화살", "C 둘 다"]):
        obs_hits, exp, var, n = 0, 0.0, 0.0, 0
        for r in sub.itertuples():
            a1, b, c = rules(r.year_pillar, r.month_pillar, r.day_pillar)
            hit = (a1, b, c)[j]
            tab = year_table(int(r.year))
            if drop_near:
                tab = tab[~tab[:, 3]]
            p = tab[:, j].mean()
            obs_hits += int(hit)
            exp += p
            var += p * (1 - p)
            n += 1
        z = (obs_hits - exp) / var ** 0.5
        res[rule] = dict(n=n, obs=obs_hits, obs_pct=100 * obs_hits / n,
                         exp_pct=100 * exp / n, z=z, p=2 * stats.norm.sf(abs(z)))
    return name, res


p = pd.read_csv(SRC)
out = []
for name, sub, drop in [
    ("주 분석: 전체", p, False),
    ("민감도: 절기 근처 날 제외(사람·기준 모두)", p[~p.near_jie_day], True),
]:
    out.append(evaluate(sub, name, drop))

lines = ["| 분석 | 조건 | N | 연예인 해당 % | 달력 기대 % | z | p | 보정 기준(0.0167) |", "|---|---|---|---|---|---|---|---|"]
for name, res in out:
    for rule, r in res.items():
        verdict = "통과" if r["p"] < 0.05 / 3 else "통과 못 함"
        lines.append(f"| {name} | {rule} | {r['n']:,} | {r['obs_pct']:.1f} | {r['exp_pct']:.1f} | {r['z']:.2f} | {r['p']:.3f} | {verdict} |")
open(OUT_MD, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("\n".join(lines))
